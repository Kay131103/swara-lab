-- MeloMaster PostgreSQL schema.
-- Apply with: psql "$POSTGRES_URL" -f login_email_verification.sql

CREATE TABLE IF NOT EXISTS tbl_user (
  tbl_user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name varchar(255) NOT NULL,
  last_name varchar(255) NOT NULL,
  contact_number varchar(32) NOT NULL DEFAULT '',
  email varchar(255) NOT NULL UNIQUE,
  username varchar(64) NOT NULL UNIQUE,
  password varchar(255) NOT NULL,
  verification_code varchar(6) NOT NULL,
  verified boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS transcription_jobs (
  id char(32) PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES tbl_user (tbl_user_id) ON DELETE CASCADE,
  audio_ext varchar(8) NOT NULL,
  audio_size_bytes bigint NOT NULL DEFAULT 0 CHECK (audio_size_bytes >= 0),
  midi_size_bytes bigint NOT NULL DEFAULT 0 CHECK (midi_size_bytes >= 0),
  audio_blob_path text,
  midi_blob_path text,
  status varchar(16) NOT NULL DEFAULT 'processing'
    CHECK (status IN ('processing', 'completed', 'failed')),
  notes_json jsonb,
  error_message varchar(255),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_jobs_user_created
  ON transcription_jobs (user_id, created_at);

CREATE TABLE IF NOT EXISTS app_sessions (
  session_id varchar(128) PRIMARY KEY,
  session_data text NOT NULL,
  expires_at timestamptz NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_app_sessions_expires
  ON app_sessions (expires_at);
